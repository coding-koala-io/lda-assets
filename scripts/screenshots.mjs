export function outputPath(page, width) {
  if (!PAGES.some(entry => entry.name === page) || !WIDTHS.includes(width)) throw new Error('Unknown screenshot page or width');
  return OUTPUT_DIR + '/' + page + '-' + width + '.png';
}

export function pageRoute(page, demo) {
  return page.route.replace(/\{(\w+)\}/g, (_, key) => {
    if (!demo[key]) throw new Error('Missing demo route value: ' + key);
    return encodeURIComponent(demo[key]);
  });
}

export function manifest() {
  return '# Local Assets screenshots\n\nGenerated by npm run screenshots from the live checkout with made-up demo content. Built by Coding Koala.\n\n'
    + '| File | Page | Width (px) |\n| --- | --- | --- |\n'
    + PAGES.flatMap(page => WIDTHS.map(width => '| [' + page.name + '-' + width + '.png](' + page.name + '-' + width + '.png) | '
      + page.route + (page.form ? ' (POST' + (page.form.action ? ': ' + page.form.action : '') + ')' : '') + ' | ' + width + ' |')).join('\n')
    + '\n\nEach release requires an independent visual check of every image at its native width: whole screen, readable text, no clipped content. Record the reviewer and result in the release review.\n';
}

export async function findBrowser(env = process.env, platform = process.platform) {
  const candidates = env.LDA_SCREENSHOT_BROWSER ? [env.LDA_SCREENSHOT_BROWSER] : platform === 'win32' ? [
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
    path.join(env.LOCALAPPDATA || homedir(), 'Google/Chrome/Application/chrome.exe'),
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  ] : platform === 'darwin' ? [
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    path.join(homedir(), 'Applications/Google Chrome.app/Contents/MacOS/Google Chrome'),
  ] : ['/usr/bin/chromium', '/usr/bin/chromium-browser', '/usr/bin/google-chrome', '/usr/bin/google-chrome-stable', '/opt/google/chrome/chrome', '/usr/bin/microsoft-edge', '/opt/microsoft/msedge/msedge', '/snap/bin/chromium'];
  for (const candidate of candidates) {
    try { await access(candidate); return candidate; } catch { /* Try the next installed browser. */ }
  }
  throw new Error('No Chromium browser found. Set LDA_SCREENSHOT_BROWSER to an installed Chrome, Edge or Chromium executable. Nothing was installed.');
}

const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
async function inventory(directory) {
  const entries = await readdir(directory).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
  return new Map(await Promise.all(entries.filter(name => name.endsWith('.png')).sort().map(async name => [name, hash(await readFile(path.join(directory, name)))])));
}

export function changes(before, after) {
  return [...new Set([...before.keys(), ...after.keys()])].sort().map(file => ({file,
    status: !before.has(file) ? 'added' : !after.has(file) ? 'removed' : before.get(file) === after.get(file) ? 'unchanged' : 'changed'}));
}

export function assertSafeCaptureText(text, scratch, {username = userInfo().username, home = homedir()} = {}) {
  const suffix = path.basename(scratch).replace(/^lda-assets-screens-/, '');
  // Match the literal username, including in form values. Normalize home path
  // case and separators, since Windows can render the same path either way.
  const normalized = text.replaceAll('\\', '/').toLowerCase();
  const forbidden = [
    ['OS username', username && text.includes(username)],
    ['home folder', home && normalized.includes(home.replaceAll('\\', '/').toLowerCase())],
    ['temporary directory suffix', suffix && text.includes(suffix)],
  ];
  for (const [kind, found] of forbidden) if (found) throw new Error('Screenshot privacy check failed: ' + kind);
}

const demoOptions = directory => ({host: '127.0.0.1', tenantsFile: path.join(directory, 'tenants.json'),
  dataDir: path.join(directory, 'data'), logDir: ':memory:', adminUser: '', adminPassword: '',
  publicBaseUrl: '', publicHostnames: '', allowRemoteApi: false, logBodies: false,
  requestTime: () => DEMO_TIME, logger: quiet});

async function closeServer(server) {
  await new Promise((resolve, reject) => {
    server.close(error => error ? reject(error) : resolve()); server.closeAllConnections();
  });
}

export async function prepareDemo(directory) {
  // Generate sample bytes through the live public routes, then save a fixed
  // demo dataset BEFORE the capture server loads it. No page content is edited.
  const server = await startServer({...demoOptions(directory), port: 0});
  let demo, state, files;
  try {
    demo = await seed('http://127.0.0.1:' + server.address().port);
    const store = server.tenants.get(demo.tenant).store;
    state = structuredClone(store.state);
    files = store.assets.map(asset => store.readFile(asset));
  } finally { await closeServer(server); }
  const entities = [...state.folders, ...state.assets];
  const ids = new Map(entities.map((entity, index) => [entity.id, hash('lda-assets-demo-' + index).slice(0, 32)]));
  for (const folder of state.folders) {
    folder.id = ids.get(folder.id); folder.parentId = ids.get(folder.parentId) ?? null;
  }
  for (const [index, asset] of state.assets.entries()) {
    asset.id = ids.get(asset.id); asset.folderId = ids.get(asset.folderId);
    asset.createdAt = DEMO_TIME; asset.modifiedAt = DEMO_TIME;
    await writeFile(path.join(directory, 'data', demo.tenant, 'files', asset.id + '.' + asset.ext), files[index]);
  }
  await writeFile(path.join(directory, 'data', demo.tenant, 'assets.json'), JSON.stringify(state, null, 2) + '\n');
  return {tenant: demo.tenant, asset: ids.get(demo.asset), document: ids.get(demo.document)};
}

export async function openDemo(directory, demo, {port = DEMO_PORT} = {}) {
  // A fresh server per image gives request tables the same genuine request
  // sequence, independent of earlier browser resource completion order.
  // The real port is fixed because it appears in CMS settings and Host headers.
  // Fail if occupied; silently choosing another port would change the images.
  const server = await startServer({...demoOptions(directory), port});
  const base = 'http://127.0.0.1:' + server.address().port;
  try {
    // Do not reuse Node's pooled connections across restarts on the same port.
    const options = {headers: {Connection: 'close'}, signal: AbortSignal.timeout(10000)};
    const home = await (await fetch(base, options)).text();
    const csrf = /name="csrf" value="([a-f0-9]+)"/.exec(home)?.[1];
    if (!csrf) throw new Error('Demo setup: missing CSRF form');
    const response = await fetch(base + '/tenants/' + demo.tenant + '/stats', {...options, signal: AbortSignal.timeout(10000)});
    await response.text();
    if (!response.ok) throw new Error('Demo setup: stats request failed');
    return {server, base, demo: {...demo, csrf, request: '1'}};
  } catch (error) { await closeServer(server); throw error; }
}

export async function configureBrowser(cdp) {
  await cdp.send('Emulation.setTimezoneOverride', {timezoneId: 'UTC'});
  await cdp.send('Emulation.setLocaleOverride', {locale: 'en-US'});
  // All timestamps here are rendered as ISO text on the server; there is no
  // page-script relative-time display, so no browser Date injection is needed.
}

export async function checkPagePrivacy(cdp, scratch) {
  cdp.step('evaluate: privacy');
  const text = await cdp.evaluate('document.body.innerText + "\\n" + '
    + '[...document.querySelectorAll("input:not([type=hidden]), textarea, select")].map(field => field.value).join("\\n")');
  assertSafeCaptureText(text, scratch);
}

// Commands time out, and a closed browser rejects outstanding commands.
export class DevTools {
  static async connect(url) {
    const socket = new WebSocket(url);
    try { await once(socket, 'open', {signal: AbortSignal.timeout(10000)}); }
    catch { socket.close(); throw new Error('browser @ n/a [connect]: Cannot connect to browser DevTools in this environment'); }
    return new DevTools(socket);
  }
  constructor(socket, {timeout = 30000, debug = process.env.LDA_SCREENSHOT_DEBUG === '1', log = console.log} = {}) {
    this.socket = socket; this.id = 0; this.pending = new Map();
    this.timeout = timeout; this.debug = debug; this.log = log;
    this.step('setup', 'browser', null);
    socket.addEventListener('message', event => {
      const message = JSON.parse(event.data);
      const pending = this.pending.get(message.id);
      if (!pending) return;
      clearTimeout(pending.timer); this.pending.delete(message.id);
      if (message.error) pending.reject(new Error(pending.context + ': DevTools: ' + message.error.message));
      else pending.resolve(message.result);
    });
    socket.addEventListener('close', () => {
      for (const pending of this.pending.values()) { clearTimeout(pending.timer); pending.reject(new Error(pending.context + ': Chromium DevTools disconnected; the browser could not remain running in this environment')); }
      this.pending.clear();
    });
  }
  step(step, page = this.page, width = this.width) {
    this.page = page; this.width = width;
    this.context = page + ' @ ' + (width === null ? 'n/a' : width + 'px') + ' [' + step + ']';
    if (this.debug) this.log('[screenshots] ' + this.context);
  }
  send(method, params = {}) {
    const context = this.context;
    return new Promise((resolve, reject) => {
      if (this.socket.readyState !== WebSocket.OPEN) return reject(new Error(context + ': Chromium DevTools is not connected'));
      const id = ++this.id;
      const timer = setTimeout(() => { this.pending.delete(id); reject(new Error(context + ': DevTools timed out: ' + method)); }, this.timeout);
      this.pending.set(id, {resolve, reject, timer, context});
      try { this.socket.send(JSON.stringify({id, method, params})); }
      catch (error) { clearTimeout(timer); this.pending.delete(id); reject(new Error(context + ": " + error.message, {cause: error})); }
    });
  }
  async evaluate(expression) {
    const context = this.context;
    const result = await this.send('Runtime.evaluate', {expression, awaitPromise: true, returnByValue: true});
    if (result.exceptionDetails) throw new Error(context + ': Screenshot page evaluation failed');
    return result.result.value;
  }
  close() { this.socket.close(); }
}

async function seed(base) {
  const request = async (route, options) => {
    const response = await fetch(base + route, {redirect: 'manual', signal: AbortSignal.timeout(10000), ...options});
    const text = await response.text();
    if (response.status >= 400) throw new Error('Demo setup failed: ' + route + ' (HTTP ' + response.status + ')');
    return {response, text};
  };
  const {text: home} = await request('/');
  const csrf = /name="csrf" value="([a-f0-9]+)"/.exec(home)?.[1];
  if (!csrf) throw new Error('Demo setup: missing CSRF form');
  const form = (route, values = {}) => request(route, {method: 'POST', headers: {'Content-Type': 'application/x-www-form-urlencoded', Origin: base}, body: new URLSearchParams({csrf, ...values})});
  await form('/tenants', {name: 'Demo library'});
  const tenant = 'demo-library'; const root = '/tenants/' + tenant;
  // Replace generated throwaway credentials with explicitly fictional values via
  // the public edit route. Never read any existing tenant or credential file.
  await form(root + '/edit', {id: tenant, name: 'Demo library', clientId: 'demo-only-client', clientSecret: 'demo-only-not-a-secret'});
  await form(root + '/samples');
  await form(root + '/folders', {name: 'Illustrations'});
  const {text: library} = await request(root);
  const assets = [...library.matchAll(/href="\/tenants\/demo-library\/assets\/([a-f0-9]{32})"/g)].map(match => match[1]);
  if (assets.length < 4) throw new Error('Demo setup: sample assets missing');
  await form(root + '/assets/' + assets[0] + '/edit', {title: 'Amber field', description: 'A made-up landscape illustration for a local demo.', altText: 'An amber field illustration', tags: 'demo, illustration'});
  await request(root + '/stats');
  const {text: detail} = await request(root);
  const requestId = /href="\/tenants\/demo-library\/request\/(\d+)">\/tenants\/demo-library\/stats</.exec(detail)?.[1];
  if (!requestId) throw new Error('Demo setup: request detail missing');
  return {tenant, asset: assets[0], document: assets[3], request: requestId, csrf};
}

async function navigate(cdp, base, page, demo) {
  // Preserve the actual server-rendered UI: no injected styles, mocked HTML,
  // hidden version labels, or substitutions in the captured screen.
  const url = base + pageRoute(page, demo);
  const target = page.form ? base + '/tenants/' + demo.tenant : url;
  cdp.step('navigate: open');
  const result = await cdp.send('Page.navigate', {url: target});
  if (result.errorText) throw new Error('Cannot open ' + page.name + ': ' + result.errorText);
  await waitReady(cdp, target);
  if (page.form) {
    cdp.step('navigate: submit POST');
    await cdp.evaluate('(() => { const form = document.createElement("form"); form.method = "POST"; form.action = ' + JSON.stringify(url) + ';'
      + 'for (const [name, value] of Object.entries(' + JSON.stringify({csrf: demo.csrf, ...page.form}) + ')) {'
      + 'const input = document.createElement("input"); input.type = "hidden"; input.name = name; input.value = value; form.append(input); }'
      + 'document.body.append(form); form.submit(); })()');
    await waitReady(cdp, url);
  }
}

// A background/headless target can suspend animation frames. Capture itself
// forces rendering; do not make readiness depend indefinitely on frame delivery.
async function waitPaint(cdp) {
  await cdp.evaluate('new Promise(resolve => { const timer = setTimeout(resolve, 250);'
    + 'requestAnimationFrame(() => requestAnimationFrame(() => { clearTimeout(timer); resolve(); })); })');
}

export async function waitReady(cdp, url) {
  cdp.step('navigate: document ready');
  for (let attempt = 0; attempt < 200; attempt++) {
    if (await cdp.evaluate('location.href === ' + JSON.stringify(url) + ' && document.readyState === "complete" && !!document.querySelector("footer")')) {
      cdp.step('evaluate: fonts');
      await cdp.evaluate('document.fonts.ready.then(() => true)');
      cdp.step('evaluate: images');
      // The library is below the fold on the instance page. decode() alone
      // does not start deferred lazy requests, so waiting before viewport
      // expansion can deadlock. Load every real image for this full-page shot.
      await cdp.evaluate('(async () => { const images = [...document.images];'
        + 'for (const image of images) image.loading = "eager";'
        + 'await Promise.all(images.map(image => image.decode().catch(() => {}))); })()');
      cdp.step('evaluate: paint');
      await waitPaint(cdp);
      return;
    }
    await delay(50);
  }
  throw new Error(cdp.context + ': Screenshot page did not finish loading');
}

async function stopBrowser(child, exited) {
  if (!child.pid || child.exitCode !== null || child.signalCode !== null) return;
  child.kill();
  await Promise.race([exited, delay(5000)]);
  if (child.exitCode === null && child.signalCode === null) { child.kill('SIGKILL'); await exited; }
}

export async function screenshots({browserEnv, checkoutIdentity, removeDirectory = rm} = {}) {
  // Fail before touching output or data when no installed browser is available.
  const browserPath = await findBrowser(browserEnv);
  const output = path.join(repoRoot, OUTPUT_DIR); const before = await inventory(output);
  const scratch = await mkdtemp(path.join(tmpdir(), 'lda-assets-screens-'));
  let server, child, exited, cdp, ownsDemo = false;
  const errors = [];
  const signals = ['SIGINT', 'SIGTERM', 'SIGBREAK'];
  const abort = new AbortController();
  const interrupted = () => abort.abort(new Error('Screenshots interrupted'));
  for (const signal of signals) process.on(signal, interrupted);
  try {
    // TenantRegistry resolves this path; the dashboard displays it verbatim.
    // Use a stable repository-owned path, separate from the random user temp path.
    assertSafeCaptureText(path.join(demoDirectory, 'tenants.json'), scratch, checkoutIdentity);
    await mkdir(path.dirname(demoDirectory), {recursive: true});
    await mkdir(demoDirectory); // Exclusive ownership: refuse existing data/runs.
    ownsDemo = true;
    const fixture = await prepareDemo(demoDirectory);
    const profile = path.join(scratch, 'browser');
    child = spawn(browserPath, ['--headless=new', '--remote-debugging-address=127.0.0.1', '--remote-debugging-port=0', '--user-data-dir=' + profile, '--no-first-run', '--no-default-browser-check', '--disable-background-networking', '--disable-component-update', '--disable-sync', '--disable-extensions', '--hide-scrollbars', 'about:blank'], {windowsHide: true, stdio: 'ignore'});
    let launchError;
    child.on('error', error => { launchError = error; });
    exited = new Promise(resolve => child.once('exit', resolve));
    let port;
    for (let attempt = 0; attempt < 200; attempt++) {
      abort.signal.throwIfAborted();
      if (launchError || child.exitCode !== null) throw new Error('Chromium could not start in this environment');
      try { port = Number((await readFile(path.join(profile, 'DevToolsActivePort'), 'utf8')).split('\n')[0]); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (port) break;
      await delay(50);
    }
    if (!port) throw new Error('Chromium DevTools was not reachable in this environment');
    const targets = await (await fetch('http://127.0.0.1:' + port + '/json/list', {signal: AbortSignal.timeout(5000)})).json();
    const target = targets.find(target => target.type === 'page');
    if (!target) throw new Error('Chromium did not open a page target');
    cdp = await DevTools.connect(target.webSocketDebuggerUrl);
    await cdp.send('Page.enable');
    await configureBrowser(cdp);
    const staged = path.join(scratch, 'captures'); await mkdir(staged);
    for (const page of PAGES) for (const width of WIDTHS) {
      abort.signal.throwIfAborted();
      const captureDemo = await openDemo(demoDirectory, fixture);
      server = captureDemo.server;
      cdp.step('layout: initial viewport', page.name, width);
      await cdp.send('Emulation.setDeviceMetricsOverride', {width, height: 900, deviceScaleFactor: 1, mobile: false});
      await navigate(cdp, captureDemo.base, page, captureDemo.demo);
      cdp.step('layout: measure');
      let {cssContentSize} = await cdp.send('Page.getLayoutMetrics');
      let height = Math.ceil(cssContentSize.height);
      // Expand the viewport to the measured page height before capture.
      if (height > 900) {
        cdp.step('layout: expand viewport');
        await cdp.send('Emulation.setDeviceMetricsOverride', {width, height, deviceScaleFactor: 1, mobile: false});
        cdp.step('layout: paint');
        await waitPaint(cdp);
        cdp.step('layout: remeasure');
        ({cssContentSize} = await cdp.send('Page.getLayoutMetrics'));
        height = Math.ceil(cssContentSize.height);
      }
      if (Math.ceil(cssContentSize.width) > width) throw new Error(page.name + ' overflows at ' + width + 'px; fix the live page before capturing it');
      await checkPagePrivacy(cdp, scratch);
      cdp.step('capture: PNG');
      const capture = await cdp.send('Page.captureScreenshot', {format: 'png', captureBeyondViewport: true, fromSurface: true, clip: {x: 0, y: 0, width, height, scale: 1}});
      const bytes = Buffer.from(capture.data, 'base64');
      // Check PNG dimensions independently of the request. This mechanical check
      // supplements the required independent visual review.
      cdp.step('evaluate: verify capture');
      const check = await cdp.evaluate('(() => { const footer = document.querySelector("footer").getBoundingClientRect();'
        + 'return {bottom: footer.bottom + scrollY, brokenImages: [...document.images].some(i => !i.complete || !i.naturalWidth), textSize: parseFloat(getComputedStyle(document.body).fontSize)}; })()');
      if (bytes.toString('hex', 0, 8) !== '89504e470d0a1a0a' || bytes.readUInt32BE(16) !== width || bytes.readUInt32BE(20) !== height || check.bottom > height || check.brokenImages || check.textSize < 14) throw new Error('Screenshot verification failed: ' + page.name + '-' + width + '.png');
      const file = path.basename(outputPath(page.name, width));
      await writeFile(path.join(staged, file), bytes);
      console.log('Checked ' + file + ': ' + width + ' x ' + height + '; footer included, images loaded, body text ' + check.textSize + 'px');
      await closeServer(server); server = null;
    }
    // Publish only after all pages pass; a browser failure preserves prior images.
    await mkdir(output, {recursive: true});
    const expected = new Set(PAGES.flatMap(page => WIDTHS.map(width => path.basename(outputPath(page.name, width)))));
    for (const file of expected) await writeFile(path.join(output, file), await readFile(path.join(staged, file)));
    for (const file of before.keys()) if (!expected.has(file)) await rm(path.join(output, file));
    await writeFile(path.join(output, 'MANIFEST.md'), manifest());
    console.log('\nBefore/after screenshot files:');
    for (const {status, file} of changes(before, await inventory(output))) console.log(status + ': ' + OUTPUT_DIR + '/' + file);
    console.log('Release check: independently review every image at its native width and log the reviewer and result.');
  } catch (error) {
    errors.push(error);
  } finally {
    try {
      if (cdp) {
        cdp.step('shutdown', 'browser', null);
        try { await cdp.send('Browser.close'); } catch { /* Browser may already have exited. */ }
        cdp.close();
      }
    } catch (error) {
      errors.push(error);
    } finally {
      try {
        if (child) await stopBrowser(child, exited);
      } catch (error) {
        errors.push(error);
      } finally {
        try {
          if (server) await closeServer(server);
        } catch (error) {
          errors.push(error);
        } finally {
          try {
            // Remove only this invocation's unique directory.
            if (path.dirname(scratch) !== path.resolve(tmpdir()) || !path.basename(scratch).startsWith('lda-assets-screens-')) throw new Error('Unsafe screenshot cleanup path');
            await removeDirectory(scratch, {recursive: true, force: true, maxRetries: 8, retryDelay: 250});
          } catch (error) {
            errors.push(error);
          } finally {
            try {
              if (ownsDemo) {
                if (path.resolve(demoDirectory) !== path.join(repoRoot, '.test-runtime', 'screenshots-demo')) throw new Error('Unsafe demo cleanup path');
                await removeDirectory(demoDirectory, {recursive: true, force: true, maxRetries: 8, retryDelay: 250});
              }
            } catch (error) {
              errors.push(error);
            } finally {
              for (const signal of signals) process.off(signal, interrupted);
            }
          }
        }
      }
    }
  }
  if (errors.length === 1) throw errors[0];
  if (errors.length > 1) throw new AggregateError(errors, errors.map(error => error.message).join('\n'));
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { await screenshots(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
